function LadderCarDetailConfig.GetAllCarByType(carType)
  if not carType then
    log_error(bWriteLog and "[cw] carType is nil, please check it")
    return {}
  end
  if type(carType) == "string" then
    carType = Enum_CarEnumNum[carType]
    if not carType then
      log_error(bWriteLog and "[cw] carType(string) is illegal, please check it")
    end
  end
  local res = {}
  for k, v in pairs(LadderCarDetailConfig.Dic_CarDetail) do
    if v.CarEnumNum & carType > 0 then
      table.insert(res, k)
    end
  end
  return res
end
local _CheckIfIdMatchType = function(nId, sCheckTypeName)
  if nId == nil or math.tointeger(nId) == nil then
    log_error(bWriteLog and "[cw] nId is nil or illegal string, it doesn't make any sense. Please type correct nId")
    return false
  end
  if sCheckTypeName == nil or type(sCheckTypeName) ~= "string" then
    log_error(bWriteLog and "[cw] sCheckTypeName is nil, it doesn't make any sense. Please type correct sCheckTypeName")
    return false
  end
  local carDetail = LadderCarDetailConfig.Dic_CarDetail[tonumber(nId)]
  if carDetail == nil then
    log(bWriteLog and "[cw] " .. tostring(nId) .. " is not in the Dic_CarDetail.")
    return false
  end
  local CarEnumNum = carDetail.CarEnumNum
  if not CarEnumNum or type(CarEnumNum) ~= "number" then
    log_error(bWriteLog and "[cw] Please check the config base on the id:" .. tostring(nId))
    return false
  end
  local targetCarEnumNum = Enum_CarEnumNum[sCheckTypeName] or 0
  local checkRes = targetCarEnumNum & CarEnumNum
  log(bWriteLog and "[cw] targetCarEnumNum(" .. tostring(targetCarEnumNum) .. ") & CarEnumNum(" .. tostring(CarEnumNum) .. ") = " .. tostring(checkRes))
  return 0 < checkRes
end
