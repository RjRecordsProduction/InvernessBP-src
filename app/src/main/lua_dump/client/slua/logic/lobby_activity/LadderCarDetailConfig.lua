function LadderCarDetailConfig.CheckHowManyCarGotBySeries(series)
  local list = {}
  local wardrobe_data = require("client.slua.logic.wardrobe.wardrobe_data")
  local cars = LadderCarDetailConfig.GetAllCarByType(series)
  for _, v in pairs(cars) do
    local tCarData = wardrobe_data:GetHallDepotItemDataByResID(v)
    local bIsLock = tCarData and tCarData.lock_cnt and tCarData.lock_cnt > 0
    if wardrobe_data:HasItem(v, true) and not bIsLock then
      table.insert(list, v)
    end
  end
  return #list, list
end
