function PufferODPakDelList._Match(tableData, deleteVerCfg)
  local key = tableData.versionSaveKey
  if key ~= nil then
    PufferODPakDelList.versionMap[key] = true
    local saveVersion = tonumber(deleteVerCfg[key]) or 0
    log(bWriteLog and "PufferODPakDelList._Match. key = " .. tostring(key) .. " saveVersion = " .. tostring(saveVersion))
    if saveVersion < tableData.appVersion then
      log(bWriteLog and "PufferODPakDelList._Match. version match")
      local regionMatch = false
      local typeRegion = type(tableData.region)
      if typeRegion == "nil" then
        regionMatch = true
      elseif typeRegion == "function" then
        regionMatch = tableData.region()
      elseif typeRegion == "string" then
        local publishRegion = Client.GetPublishRegion()
        regionMatch = tableData.region == publishRegion
      end
      if regionMatch then
        log(bWriteLog and "PufferODPakDelList._Match. region match")
        local platformName = Client.GetDevicePlatformName()
        if tableData.platform == nil or tableData.platform == platformName then
          log(bWriteLog and "PufferODPakDelList._Match. platform match")
          return true
        end
      end
    end
  end
  return false
end
function PufferODPakDelList.DeleteFileList()
  if PufferODPakDelList.cfgData then
    local PlayerPrefsSystem = require("client.logic.LogicPlayerPrefs.playerprefs")
    local deleteVerCfg = PlayerPrefsSystem.LoadFileToTable_N(PlayerPrefsSystem.ePlayerPrefsType.eODPakDeleteOldFileVersion) or {}
    local PufferDeleteManager = require("client.slua.logic.download.delete.puffer_delete_manager")
    PufferDeleteManager.ignoreFileDeleteNotify = true
    local version_util = require("client.common.version_util")
    local appVersion = version_util.GetCurVersionNumber()
    log(bWriteLog and "appVersion = " .. tostring(appVersion))
    local PufferConst = require("client.slua.logic.download.puffer_const")
    PufferODPakDelList.versionMap = {}
    for i, tableData in ipairs(PufferODPakDelList.cfgData) do
      if PufferODPakDelList._Match(tableData, deleteVerCfg, appVersion) then
        PufferDownloader.GEMReportSubEvent("deleteFileListMatch", {
          tostring(tableData.appVersion),
          tostring(tableData.versionSaveKey),
          tostring(tableData.platform),
          tostring(tableData.region)
        })
        log(bWriteLog and "PufferODPakDelList.DeleteFileList. delete " .. tostring(i))
        for _, pakName in ipairs(tableData.list) do
          local DelPakPath = Client.ProjectSavedDir() .. PufferConst.PAKS_RELATIVE_DIR .. pakName
          if Client.IsFileExistsWithOutPakCheck(DelPakPath) then
            log(bWriteLog and "PufferODPakDelList.DeleteFileList. DelPakPath = " .. DelPakPath)
            if GCPufferDownloader.DeleteFile(DelPakPath) then
              Client.AddCrashContextData(30, pakName, false, 1200)
              local deleteSize = Client.GetFileSizeOnDiskBytes(DelPakPath) / PufferConst.MB
              PufferDownloader.AddDeleteSize(deleteSize)
            end
            Client.USFSDeletePkg_V2(pakName)
          end
        end
      end
    end
    for k, v in pairs(PufferODPakDelList.versionMap) do
      deleteVerCfg[k] = appVersion
    end
    log_tree("deleteVerCfg = ", deleteVerCfg)
    PufferDeleteManager.ignoreFileDeleteNotify = false
    PlayerPrefsSystem.SaveTableToFile_N(deleteVerCfg, PlayerPrefsSystem.ePlayerPrefsType.eODPakDeleteOldFileVersion)
  end
end
function PufferODPakDelList.DeleteSYSOldFiles()
  PufferODPakDelList.DeleteSYSOldFilesForBigSize()
  local DeleteSYSOldFileVersion = HDmpveRemote.HDmpveRemoteConfigGetString("USFDeleteSYSOldFileVersion", "")
  if #DeleteSYSOldFileVersion <= 0 then
    log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFiles return for empty key")
    return
  end
  Client.AddAttachFileString("DeleteSYSOldFileVersion", false, "DeleteSYSOldFileVersion:" .. tostring(DeleteSYSOldFileVersion))
  local PlayerPrefsSystem = require("client.logic.LogicPlayerPrefs.playerprefs")
  local deleteVerCfg = PlayerPrefsSystem.LoadFileToTable_N(PlayerPrefsSystem.ePlayerPrefsType.eODPakDeleteOldFileVersion) or {}
  local key = DeleteSYSOldFileVersion
  if deleteVerCfg[key] then
    log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFiles return for key = " .. key)
    return
  end
  Client.AddAttachFileString("DeleteSYSOldFileVersion", false, "DeleteSYSOldFileVersion:" .. "DeleteCachePaks")
  local PufferDeleteManager = require("client.slua.logic.download.delete.puffer_delete_manager")
  PufferDeleteManager.ignoreFileDeleteNotify = true
  local PufferConst = require("client.slua.logic.download.puffer_const")
  local FlagFilePath = Client.ProjectSavedDir() .. PufferDownloader.DOWNLOAD_CACHEPAKS_RELATIVE .. tostring(1) .. ".pak"
  log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFiles FlagFilePath: " .. FlagFilePath)
  if Client.IsFileExistsWithOutPakCheck(FlagFilePath) then
    log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFiles delete for key = " .. key)
    Client.DeleteDirectory(Client.ProjectSavedDir() .. PufferDownloader.DOWNLOAD_CACHEPAKS_RELATIVE)
    PufferODPakDelList.CrashPostException("DeleteCachePaks", "DeleteSYSOldFileVersion", "PufferODPakDelList.DeleteSYSOldFiles() DeleteSYSOldFileVersion " .. DeleteSYSOldFileVersion)
  end
  deleteVerCfg[key] = true
  PufferDeleteManager.ignoreFileDeleteNotify = false
  PlayerPrefsSystem.SaveTableToFile_N(deleteVerCfg, PlayerPrefsSystem.ePlayerPrefsType.eODPakDeleteOldFileVersion)
end
function PufferODPakDelList.DeleteSYSOldFilesForBigSize()
  local USFDeleteSYSOldFileForSize = HDmpveRemote.HDmpveRemoteConfigGetInt("USFDeleteSYSOldFileForSize", 0)
  if USFDeleteSYSOldFileForSize <= 0 then
    log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFilesForBigSize return for USFDeleteSYSOldFileForSize: " .. tostring(USFDeleteSYSOldFileForSize))
    return
  end
  local FlagFilePath = Client.ProjectSavedDir() .. PufferDownloader.DOWNLOAD_CACHEPAKS_RELATIVE .. tostring(USFDeleteSYSOldFileForSize) .. ".pak"
  log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFilesForBigSize FlagFilePath: " .. FlagFilePath)
  if Client.IsFileExistsWithOutPakCheck(FlagFilePath) then
    log(bWriteLog and "PufferODPakDelList.DeleteSYSOldFilesForBigSize delete cachepak dir: " .. Client.ProjectSavedDir() .. PufferDownloader.DOWNLOAD_CACHEPAKS_RELATIVE)
    Client.DeleteDirectory(Client.ProjectSavedDir() .. PufferDownloader.DOWNLOAD_CACHEPAKS_RELATIVE)
    PufferODPakDelList.CrashPostException("DeleteCachePaks", "DeleteSYSOldFilesForBigSize", "PufferODPakDelList.DeleteSYSOldFilesForBigSize() Client.IsFileExistsWithOutPakCheck(FlagFilePath) " .. FlagFilePath)
  end
end
