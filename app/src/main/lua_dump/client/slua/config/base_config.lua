local MergeUndeclaredConfig = function(target, source)
  for k, v in pairs(source) do
    if target[k] == nil then
      target[k] = v
    else
      log_error("base_config MergeUndeclaredConfig duplicate key: " .. tostring(k))
    end
  end
end
